func TestGroovyInjectionIsEscaped(t *testing.T) {
	// Literal text must never be evaluated by Groovy, even when the string
	// becomes a GString because of an untranslatable-to-shell expression.
	res := convert(t, `
on: push
jobs:
  a:
    runs-on: x
    steps:
      - run: echo "${HOME}" '${{ runner.os }}' "\n"
`, Options{})
	assertContains(t, res.Jenkinsfile, `sh "echo \"\${HOME}\" '${(isUnix() ? 'Linux' : 'Windows')}' \"\\n\""`)
}
