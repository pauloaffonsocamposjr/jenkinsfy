func TestArtifactPatterns(t *testing.T) {
	tests := []struct {
		paths, root, includes string
	}{
		{"dist/", "dist", "**"},
		{"./app/dist/", "app/dist", "**"},
		{"dist", "dist", "**"},
		{"build/report.xml", "build", "report.xml"},
		{"out/**/*.jar", "out", "**/*.jar"},
		{"out/a/\nout/b/", "out", "a/**,b/**"},
		{"bin/app\nREADME.md", "", "bin/app/**,README.md"},
		{"*.log", "", "*.log"},
		{"dist/\n!dist/*.map", "dist", "**"},
	}
	for _, tt := range tests {
		root, inc := artifactPatterns(tt.paths)
		if root != tt.root || inc != tt.includes {
			t.Errorf("artifactPatterns(%q) = %q, %q; want %q, %q", tt.paths, root, inc, tt.root, tt.includes)
		}
	}
}

