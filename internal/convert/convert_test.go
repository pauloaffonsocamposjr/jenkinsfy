func TestSecrets(t *testing.T) {
	res := convert(t, `
on: push
env:
  DEPLOY_KEY: ${{ secrets.DEPLOY_KEY }}
jobs:
  a:
    runs-on: x
    env:
      API: ${{ secrets.API_TOKEN }}
    steps:
      - run: 'curl -H "Authorization: ${{ secrets.OTHER }}" https://example.com'
      - run: npm publish
        env:
          NODE_AUTH_TOKEN: ${{ secrets.NPM_TOKEN }}
          MODE: release
`, Options{})
	assertContains(t, res.Jenkinsfile,
		"DEPLOY_KEY = credentials('DEPLOY_KEY')",
		"API = credentials('API_TOKEN')",
		// Secrets referenced inline are bound once at pipeline level and
		// expanded by the shell, never by Groovy.
		"OTHER = credentials('OTHER')",
		`sh 'curl -H "Authorization: ${OTHER}" https://example.com'`,
		"withCredentials([string(credentialsId: 'NPM_TOKEN', variable: 'NODE_AUTH_TOKEN')]) {",
		"withEnv(['MODE=release']) {",
	)
	assertNotContains(t, res.Jenkinsfile, "credentials('NPM_TOKEN')\n", "API_TOKEN = credentials")
}

