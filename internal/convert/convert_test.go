func TestPostConditions(t *testing.T) {
	res := convert(t, `
on: push
jobs:
  a:
    runs-on: x
    steps:
      - run: build
      - name: Only on success
        if: success()
        run: publish
      - name: Cleanup
        if: ${{ always() }}
        run: cleanup
      - name: Alert
        if: failure()
        run: alert
      - name: Cancelled
        if: cancelled()
        run: cancelled
`, Options{})
	out := res.Jenkinsfile
	assertContains(t, out,
		"post {",
		"always {\n                    // Cleanup\n                    sh 'cleanup'",
		"failure {\n                    // Alert\n                    sh 'alert'",
		"aborted {\n                    // Cancelled\n                    sh 'cancelled'",
		"// Only on success\n                sh 'publish'",
	)
	assertNotContains(t, out, "script {")
}

