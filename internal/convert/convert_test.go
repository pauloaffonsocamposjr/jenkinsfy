var update = flag.Bool("update", false, "rewrite golden files in testdata")

func convert(t *testing.T, src string, opts Options) *Result {
	t.Helper()
	wf, err := workflow.ParseBytes([]byte(src))
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	res, err := Convert(wf, opts)
	if err != nil {
		t.Fatalf("convert: %v", err)
	}
	checkBalanced(t, res.Jenkinsfile)
	// test/jenkins/verify.sh sets this to lint every generated pipeline
	// against a real Jenkins.
	if dir := os.Getenv("JENKINSFY_DUMP_DIR"); dir != "" {
		name := strings.NewReplacer("/", "_", " ", "_").Replace(t.Name()) + ".Jenkinsfile"
		if err := os.WriteFile(filepath.Join(dir, name), []byte(res.Jenkinsfile), 0o644); err != nil {
			t.Fatalf("dump: %v", err)
		}
	}
	return res
}

// checkBalanced verifies braces and parentheses are balanced outside of
// Groovy strings and comments, as a cheap syntax sanity check.
func checkBalanced(t *testing.T, src string) {
	t.Helper()
	var stack []byte
	pairs := map[byte]byte{'}': '{', ')': '(', ']': '['}
	for i := 0; i < len(src); i++ {
		switch {
		case strings.HasPrefix(src[i:], "//"):
			for i < len(src) && src[i] != '\n' {
				i++
			}
		case strings.HasPrefix(src[i:], "'''"), strings.HasPrefix(src[i:], `"""`):
			q := src[i : i+3]
			i += 3
			for i < len(src) && !strings.HasPrefix(src[i:], q) {
				if src[i] == '\\' {
					i++
				}
				i++
			}
			i += 2
		case src[i] == '\'' || src[i] == '"':
			q := src[i]
			i++
			for i < len(src) && src[i] != q {
				if src[i] == '\\' {
					i++
				}
				if src[i] == '\n' {
					t.Fatalf("newline inside single-line string near offset %d:\n%s", i, src)
				}
				i++
			}
		case src[i] == '{' || src[i] == '(' || src[i] == '[':
			stack = append(stack, src[i])
		case src[i] == '}' || src[i] == ')' || src[i] == ']':
			if len(stack) == 0 || stack[len(stack)-1] != pairs[src[i]] {
				t.Fatalf("unbalanced %q at offset %d:\n%s", src[i], i, src)
			}
			stack = stack[:len(stack)-1]
		}
	}
	if len(stack) != 0 {
		t.Fatalf("unclosed %q:\n%s", stack, src)
	}
}

func assertContains(t *testing.T, out string, want ...string) {
	t.Helper()
	for _, w := range want {
		if !strings.Contains(out, w) {
			t.Errorf("output does not contain:\n%s\n--- output ---\n%s", w, out)
		}
	}
}

func assertNotContains(t *testing.T, out string, unwanted ...string) {
	t.Helper()
	for _, w := range unwanted {
		if strings.Contains(out, w) {
			t.Errorf("output unexpectedly contains:\n%s\n--- output ---\n%s", w, out)
		}
	}
}

func assertWarning(t *testing.T, res *Result, substr string) {
	t.Helper()
	for _, w := range res.Warnings {
		if strings.Contains(w, substr) {
			return
		}
	}
	t.Errorf("no warning containing %q; warnings: %q", substr, res.Warnings)
}

// TestGolden converts every testdata/*.yml and compares the result with the
// matching .Jenkinsfile. Run `go test ./internal/convert -update` to refresh.
func TestGolden(t *testing.T) {
	files, err := filepath.Glob("testdata/*.yml")
	if err != nil || len(files) == 0 {
		t.Fatalf("no golden inputs: %v", err)
	}
	for _, in := range files {
		t.Run(filepath.Base(in), func(t *testing.T) {
			src, err := os.ReadFile(in)
			if err != nil {
				t.Fatal(err)
			}
			res := convert(t, string(src), Options{})
			golden := strings.TrimSuffix(in, ".yml") + ".Jenkinsfile"
			if *update {
				if err := os.WriteFile(golden, []byte(res.Jenkinsfile), 0o644); err != nil {
					t.Fatal(err)
				}
				return
			}
			want, err := os.ReadFile(golden)
			if err != nil {
				t.Fatalf("%v (run with -update to create it)", err)
			}
			if res.Jenkinsfile != string(want) {
				t.Errorf("%s mismatch (run with -update to accept)\n--- got ---\n%s", golden, res.Jenkinsfile)
			}
		})
	}
}

func TestSimpleJob(t *testing.T) {
	res := convert(t, `
name: Build
on: push
jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Compile
        run: go build ./...
`, Options{})
	want := `// Generated by jenkinsfy from GitHub workflow 'Build'.
// Review every TODO(jenkinsfy) comment before using this pipeline.
// GitHub triggers: push.
// Use a Multibranch Pipeline with a GitHub/Git branch source to build these events.
pipeline {
    agent none
    stages {
        stage('build') {
            agent { label 'ubuntu-latest' }
            steps {
                checkout scm
                // Compile
                sh 'go build ./...'
            }
        }
    }
}
`
	if res.Jenkinsfile != want {
		t.Errorf("got:\n%s\nwant:\n%s", res.Jenkinsfile, want)
	}
	if len(res.Warnings) != 0 {
		t.Errorf("unexpected warnings: %v", res.Warnings)
	}
}

func TestIndependentJobsRunInParallel(t *testing.T) {
	res := convert(t, `
on: push
jobs:
  lint:
    runs-on: ubuntu-latest
    steps: [{run: make lint}]
  unit:
    runs-on: ubuntu-latest
    steps: [{run: make test}]
  package:
    needs: [lint, unit]
    runs-on: ubuntu-latest
    steps: [{run: make package}]
`, Options{})
	out := res.Jenkinsfile
	assertContains(t, out, "stage('Parallel: lint, unit') {", "parallel {")
	if strings.Index(out, "stage('package')") < strings.Index(out, "parallel {") {
		t.Errorf("package stage should come after the parallel block:\n%s", out)
	}
}

func TestDependencyOrdering(t *testing.T) {
	// Jobs are declared out of dependency order on purpose.
	res := convert(t, `
on: push
jobs:
  deploy:
    needs: build
    runs-on: x
    steps: [{run: deploy}]
  build:
    runs-on: x
    steps: [{run: build}]
`, Options{})
	out := res.Jenkinsfile
	if b, d := strings.Index(out, "stage('build')"), strings.Index(out, "stage('deploy')"); b < 0 || d < 0 || b > d {
		t.Errorf("build must precede deploy:\n%s", out)
	}
	assertNotContains(t, out, "parallel")
}

func TestDependencyCycle(t *testing.T) {
	wf, err := workflow.ParseBytes([]byte(`
on: push
jobs:
  a:
    needs: b
    runs-on: x
    steps: [{run: a}]
  b:
    needs: a
    runs-on: x
    steps: [{run: b}]
`))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := Convert(wf, Options{}); err == nil || !strings.Contains(err.Error(), "cycle") {
		t.Errorf("err = %v, want dependency cycle error", err)
	}
}

