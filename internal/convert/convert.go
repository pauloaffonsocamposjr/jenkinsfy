// Package convert turns a parsed GitHub Actions workflow into a declarative
// Jenkinsfile.
package convert

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/pauloaffonsocamposjr/jenkinsfy/internal/expr"
	"github.com/pauloaffonsocamposjr/jenkinsfy/internal/workflow"
)

// Options tune the conversion.
type Options struct {
	// LabelMap maps GitHub runner labels (e.g. "ubuntu-latest") to Jenkins
	// agent labels (e.g. "linux"). Unmapped labels are used as-is.
	LabelMap map[string]string
}

// Result is the output of a conversion.
type Result struct {
	Jenkinsfile string
	// Warnings lists constructs that were approximated or left as TODOs.
	Warnings []string
}

// Convert converts wf into a Jenkinsfile.
func Convert(wf *workflow.Workflow, opts Options) (*Result, error) {
	c := &converter{wf: wf, opts: opts, tr: expr.New()}
	out, err := c.pipeline()
	if err != nil {
		return nil, err
	}
	return &Result{Jenkinsfile: out, Warnings: c.tr.Warnings()}, nil
}

type converter struct {
	wf   *workflow.Workflow
	opts Options
	tr   *expr.Translator
}

func (c *converter) warn(format string, args ...any) { c.tr.Warn(format, args...) }

func (c *converter) pipeline() (string, error) {
	levels, err := levels(c.wf.Jobs)
	if err != nil {
		return "", err
	}

	// Stages are rendered first so that every referenced secret is known
	// before the top-level environment block is written.
	stages := &writer{depth: 2}
	for _, level := range levels {
		c.level(stages, level)
	}
	env := &writer{depth: 2}
	defined := c.envEntries(env, c.wf.Env)
	for _, s := range c.tr.Secrets() {
		if !defined[s] {
			env.line("%s = credentials(%s)", s, expr.QuoteString(s))
		}
	}

	w := &writer{}
	name := c.wf.Name
	if name == "" {
		name = "workflow"
	}
	w.line("// Generated by jenkinsfy from GitHub workflow %s.", expr.QuoteString(name))
	w.line("// Review every TODO(jenkinsfy) comment before using this pipeline.")
	c.triggerComments(w)
	w.open("pipeline")
	w.line("agent none")
	c.options(w)
	c.parameters(w)
	c.triggers(w)
	if env.b.Len() > 0 {
		w.open("environment")
		w.b.WriteString(env.String())
		w.close()
	}
	w.open("stages")
	w.b.WriteString(stages.String())
	w.close()
	w.close()
	return w.String(), nil
}

// ---------------------------------------------------------------------------
// Pipeline-level directives

func (c *converter) triggerComments(w *writer) {
	var notes []string
	for _, e := range c.wf.On.Events {
		switch e {
		case "schedule", "workflow_dispatch":
			continue
		}
		note := e
		if b := c.wf.On.Branches[e]; len(b) > 0 {
			note += " (branches: " + strings.Join(b, ", ") + ")"
		}
		notes = append(notes, note)
	}
	if len(notes) > 0 {
		w.line("// GitHub triggers: %s.", strings.Join(notes, "; "))
		w.line("// Use a Multibranch Pipeline with a GitHub/Git branch source to build these events.")
	}
}

func (c *converter) options(w *writer) {
	if c.wf.Concurrency == nil {
		return
	}
	w.open("options")
	if c.wf.Concurrency.CancelInProgress {
		w.line("disableConcurrentBuilds(abortPrevious: true)")
	} else {
		w.line("disableConcurrentBuilds()")
	}
	w.close()
}

func (c *converter) parameters(w *writer) {
	if len(c.wf.On.Inputs) == 0 {
		return
	}
	w.open("parameters")
	for _, in := range c.wf.On.Inputs {
		name, desc := expr.QuoteString(in.Name), expr.QuoteString(in.Description)
		switch in.Type {
		case "boolean":
			def := "false"
			if strings.EqualFold(in.Default, "true") {
				def = "true"
			}
			w.line("booleanParam(name: %s, defaultValue: %s, description: %s)", name, def, desc)
		case "choice":
			// Jenkins uses the first choice as the default.
			opts := []string{}
			if in.Default != "" {
				opts = append(opts, expr.QuoteString(in.Default))
			}
			for _, o := range in.Options {
				if o != in.Default {
					opts = append(opts, expr.QuoteString(o))
				}
			}
			w.line("choice(name: %s, choices: [%s], description: %s)", name, strings.Join(opts, ", "), desc)
		default:
			w.line("string(name: %s, defaultValue: %s, description: %s)", name, expr.QuoteString(in.Default), desc)
		}
	}
	w.close()
}

func (c *converter) triggers(w *writer) {
	if len(c.wf.On.Schedules) == 0 {
		return
	}
	// GitHub evaluates schedules in UTC; make Jenkins do the same.
	spec := "TZ=UTC\n" + strings.Join(c.wf.On.Schedules, "\n")
	w.open("triggers")
	w.line("cron(%s)", expr.QuoteString(spec))
	w.close()
}

// ---------------------------------------------------------------------------
// Jobs and stages

// levels groups jobs so that each job appears after everything it needs.
// Jobs in the same level are independent and can run in parallel.
func levels(jobs workflow.Jobs) ([][]*workflow.Job, error) {
	byID := map[string]*workflow.Job{}
	for _, j := range jobs {
		byID[j.ID] = j
	}
	depth := map[string]int{}
	visiting := map[string]bool{}
	var visit func(j *workflow.Job) (int, error)
	visit = func(j *workflow.Job) (int, error) {
		if d, ok := depth[j.ID]; ok {
			return d, nil
		}
		if visiting[j.ID] {
			return 0, fmt.Errorf("dependency cycle involving job %q", j.ID)
		}
		visiting[j.ID] = true
		d := 0
		for _, n := range j.Needs {
			dep, ok := byID[n]
			if !ok {
				return 0, fmt.Errorf("job %q needs unknown job %q", j.ID, n)
			}
			nd, err := visit(dep)
			if err != nil {
				return 0, err
			}
			if nd+1 > d {
				d = nd + 1
			}
		}
		visiting[j.ID] = false
		depth[j.ID] = d
		return d, nil
	}
	var out [][]*workflow.Job
	for _, j := range jobs {
		d, err := visit(j)
		if err != nil {
			return nil, err
		}
		for len(out) <= d {
			out = append(out, nil)
		}
		out[d] = append(out[d], j)
	}
	return out, nil
}

func (c *converter) level(w *writer, jobs []*workflow.Job) {
	if len(jobs) == 1 {
		c.job(w, jobs[0])
		return
	}
	for _, j := range jobs {
		if isMatrix(j) {
			// Declarative pipelines cannot nest a matrix inside parallel.
			c.warn("jobs %s run sequentially: a matrix job cannot be nested in a parallel block", jobNames(jobs))
			for _, j := range jobs {
				c.job(w, j)
			}
			return
		}
	}
	w.open("stage(%s)", expr.QuoteString("Parallel: "+jobNames(jobs)))
	w.open("parallel")
	for _, j := range jobs {
		c.job(w, j)
	}
	w.close()
	w.close()
}

func jobNames(jobs []*workflow.Job) string {
	names := make([]string, len(jobs))
	for i, j := range jobs {
		names[i] = j.ID
	}
	return strings.Join(names, ", ")
}

func isMatrix(j *workflow.Job) bool {
	return j.Strategy != nil && j.Strategy.Matrix != nil && len(j.Strategy.Matrix.Axes) > 0
}

func stageName(j *workflow.Job) string {
	if j.Name != "" && !expr.HasExpression(j.Name) {
		return j.Name
	}
	return j.ID
}

func (c *converter) job(w *writer, j *workflow.Job) {
	name := expr.QuoteString(stageName(j))
	if j.Uses != "" {
		c.warn("job %q calls reusable workflow %s, which must be converted separately", j.ID, j.Uses)
		w.open("stage(%s)", name)
		w.line("agent any")
		w.open("steps")
		w.todo("job calls reusable workflow %s", j.Uses)
		w.line("echo %s", expr.QuoteString("TODO(jenkinsfy): reusable workflow "+j.Uses))
		w.close()
		w.close()
		return
	}
	if j.Strategy != nil && j.Strategy.Matrix != nil && j.Strategy.Matrix.Expression != "" {
		c.warn("job %q: dynamic matrix %s is not supported; job converted without a matrix", j.ID, j.Strategy.Matrix.Expression)
	}
	w.open("stage(%s)", name)
	if isMatrix(j) {
		c.matrix(w, j)
		w.open("stages")
		w.open("stage(%s)", name)
		c.jobBody(w, j)
		w.close()
		w.close()
		w.close() // matrix
	} else {
		c.jobBody(w, j)
	}
	w.close()
}

// matrix opens a matrix block and writes its axes; the caller closes it.
func (c *converter) matrix(w *writer, j *workflow.Job) {
	m := j.Strategy.Matrix
	if len(m.Include) > 0 {
		c.warn("job %q: matrix 'include' entries are not supported and were ignored", j.ID)
	}
	if j.Strategy.MaxParallel > 0 {
		c.warn("job %q: matrix max-parallel is not supported", j.ID)
	}
	w.open("matrix")
	w.open("axes")
	for _, a := range m.Axes {
		w.open("axis")
		w.line("name %s", expr.QuoteString(expr.EnvName(a.Name)))
		w.line("values %s", quoteList(a.Values))
		w.close()
	}
	w.close()
	if len(m.Exclude) > 0 {
		w.open("excludes")
		for _, ex := range m.Exclude {
			w.open("exclude")
			for _, kv := range ex {
				w.open("axis")
				w.line("name %s", expr.QuoteString(expr.EnvName(kv.Key)))
				w.line("values %s", expr.QuoteString(kv.Value))
				w.close()
			}
			w.close()
		}
		w.close()
	}
}

func quoteList(values []string) string {
	q := make([]string, len(values))
	for i, v := range values {
		q[i] = expr.QuoteString(v)
	}
	return strings.Join(q, ", ")
}

func (c *converter) jobBody(w *writer, j *workflow.Job) {
	c.agent(w, j)

	env := append(workflow.OrderedMap{}, j.Env...)
	if j.Container != nil {
		env = append(env, j.Container.Env...)
	}
	if len(env) > 0 {
		w.open("environment")
		c.envEntries(w, env)
		w.close()
	}
	if j.TimeoutMinutes > 0 {
		w.open("options")
		w.line("timeout(time: %d, unit: 'MINUTES')", j.TimeoutMinutes)
		w.close()
	}
	if j.If != "" {
		if cond, err := c.tr.Condition(j.If); err != nil {
			c.warn("job %q: could not translate condition %q: %v; stage is skipped until fixed", j.ID, j.If, err)
			w.open("when")
			w.todo("translate condition: %s", j.If)
			w.line("expression { return false }")
			w.close()
		} else {
			w.open("when")
			w.line("beforeAgent true")
			w.line("expression { return %s }", cond)
			w.close()
		}
	}
	if !j.Services.IsZero() {
		c.warn("job %q: service containers are not supported; start them in the agent or use docker.image().withRun()", j.ID)
	}
	if len(j.Outputs) > 0 {
		c.warn("job %q: job outputs are not supported; pass values with stash/unstash or files", j.ID)
	}

	var main []workflow.Step
	post := map[string][]workflow.Step{}
	for _, s := range j.Steps {
		if cond := postCondition(s.If); cond != "" {
			post[cond] = append(post[cond], s)
			continue
		}
		main = append(main, s)
	}

	w.open("steps")
	if j.ContinueOnError {
		w.open("catchError(buildResult: 'SUCCESS', stageResult: 'UNSTABLE')")
	}
	if len(main) == 0 {
		w.line("echo 'No steps'")
	}
	for _, s := range main {
		c.step(w, j, s)
	}
	if j.ContinueOnError {
		w.close()
	}
	w.close()

	if len(post) > 0 {
		w.open("post")
		for _, cond := range []string{"always", "aborted", "failure", "success"} {
			if len(post[cond]) == 0 {
				continue
			}
			w.open(cond)
			for _, s := range post[cond] {
				c.step(w, j, s)
			}
			w.close()
		}
		w.close()
	}
}

// postCondition maps an `if:` that is exactly a status function onto a
// declarative post condition. `success()` is the default behaviour, so it
// stays in the main steps block.
func postCondition(cond string) string {
	switch strings.ReplaceAll(expr.Unwrap(cond), " ", "") {
	case "always()":
		return "always"
	case "failure()":
		return "failure"
	case "cancelled()":
		return "aborted"
	}
	return ""
}

func isSuccess(cond string) bool {
	return strings.ReplaceAll(expr.Unwrap(cond), " ", "") == "success()"
}

var matrixRef = regexp.MustCompile(`^\$\{\{\s*matrix\.([\w-]+)\s*\}\}$`)

func (c *converter) agent(w *writer, j *workflow.Job) {
	if j.RunsOn.Group != "" {
		c.warn("job %q: runner group %q is ignored", j.ID, j.RunsOn.Group)
	}
	var segs []expr.Segment
	for i, l := range j.RunsOn.Labels {
		if i > 0 {
			segs = append(segs, expr.Segment{Text: " && "})
		}
		if m := matrixRef.FindStringSubmatch(l); m != nil {
			// Matrix axes are plain variables inside a matrix agent block.
			segs = append(segs, expr.Segment{Text: expr.EnvName(m[1]), Groovy: true})
			if len(c.opts.LabelMap) > 0 {
				c.warn("job %q: label map is not applied to matrix-driven runs-on %s", j.ID, l)
			}
			continue
		}
		if expr.HasExpression(l) {
			segs = append(segs, c.tr.Interpolate(l, false)...)
			continue
		}
		if mapped, ok := c.opts.LabelMap[l]; ok {
			l = mapped
		}
		segs = append(segs, expr.Segment{Text: l})
	}
	label := ""
	if len(segs) > 0 {
		label = expr.GroovyString(segs)
	}

	if j.Container != nil && j.Container.Image != "" {
		w.open("agent")
		w.open("docker")
		w.line("image %s", expr.GroovyString(c.tr.Interpolate(j.Container.Image, false)))
		if j.Container.Options != "" {
			w.line("args %s", expr.QuoteString(j.Container.Options))
		}
		if label != "" {
			w.line("label %s", label)
		}
		w.close()
		w.close()
		return
	}
	if label == "" {
		w.line("agent any")
		return
	}
	w.line("agent { label %s }", label)
}

var exactSecret = regexp.MustCompile(`^\$\{\{\s*secrets\.([\w-]+)\s*\}\}$`)

// envEntries writes `KEY = value` lines for an environment block and returns
// the set of keys written.
func (c *converter) envEntries(w *writer, env workflow.OrderedMap) map[string]bool {
	keys := map[string]bool{}
	for _, kv := range env {
		keys[kv.Key] = true
		if m := exactSecret.FindStringSubmatch(kv.Value); m != nil {
			w.line("%s = credentials(%s)", kv.Key, expr.QuoteString(m[1]))
			continue
		}
		w.line("%s = %s", kv.Key, expr.GroovyString(c.tr.Interpolate(kv.Value, false)))
	}
	return keys
}

// ---------------------------------------------------------------------------
// Steps

func isWindows(j *workflow.Job) bool {
	for _, l := range j.RunsOn.Labels {
		if strings.HasPrefix(strings.ToLower(l), "windows") {
			return true
		}
	}
	return false
}

func (c *converter) step(w *writer, j *workflow.Job, s workflow.Step) {
	if s.Name != "" {
		w.line("// %s", s.Name)
	}
	depth := w.depth
	if s.If != "" && postCondition(s.If) == "" && !isSuccess(s.If) {
		cond, err := c.tr.Condition(s.If)
		if err != nil {
			c.warn("job %q: could not translate step condition %q: %v; step is disabled until fixed", j.ID, s.If, err)
			w.todo("translate condition: %s", s.If)
			cond = "false"
		}
		if cond != "true" {
			w.open("script")
			w.open("if (%s)", cond)
		}
	}
	if s.TimeoutMinutes > 0 {
		w.open("timeout(time: %d, unit: 'MINUTES')", s.TimeoutMinutes)
	}
	if s.ContinueOnError {
		w.open("catchError(buildResult: 'SUCCESS', stageResult: 'UNSTABLE')")
	}
	var creds, plain []string
	for _, kv := range s.Env {
		if m := exactSecret.FindStringSubmatch(kv.Value); m != nil {
			creds = append(creds, fmt.Sprintf("string(credentialsId: %s, variable: %s)",
				expr.QuoteString(m[1]), expr.QuoteString(kv.Key)))
			continue
		}
		segs := append([]expr.Segment{{Text: kv.Key + "="}}, c.tr.Interpolate(kv.Value, false)...)
		plain = append(plain, expr.GroovyString(segs))
	}
	if len(creds) > 0 {
		w.open("withCredentials([%s])", strings.Join(creds, ", "))
	}
	if len(plain) > 0 {
		w.open("withEnv([%s])", strings.Join(plain, ", "))
	}

	switch {
	case s.Run != "":
		dir := s.WorkingDirectory
		if dir == "" {
			dir = j.Defaults.Run.WorkingDirectory
		}
		if dir == "" {
			dir = c.wf.Defaults.Run.WorkingDirectory
		}
		if dir != "" {
			w.open("dir(%s)", expr.GroovyString(c.tr.Interpolate(dir, false)))
		}
		c.run(w, j, s)
	case s.Uses != "":
		c.uses(w, j, s)
	default:
		c.warn("job %q: step %q has neither run nor uses", j.ID, s.Name)
		w.line("echo 'Empty step'")
	}
	for w.depth > depth {
		w.close()
	}
}

func (c *converter) run(w *writer, j *workflow.Job, s workflow.Step) {
	shell := s.Shell
	if shell == "" {
		shell = j.Defaults.Run.Shell
	}
	if shell == "" {
		shell = c.wf.Defaults.Run.Shell
	}
	if shell == "" && isWindows(j) {
		shell = "pwsh"
	}
	stepName, prefix := "sh", ""
	switch shell {
	case "", "sh":
	case "bash":
		prefix = "#!/bin/bash\nset -eo pipefail\n"
	case "python":
		prefix = "#!/usr/bin/env python3\n"
	case "pwsh":
		stepName = "pwsh"
	case "powershell":
		stepName = "powershell"
	case "cmd":
		stepName = "bat"
	default:
		c.warn("job %q: custom shell %q is not supported; using sh", j.ID, shell)
	}

	script := strings.TrimRight(s.Run, "\n")
	if prefix == "" && !strings.Contains(script, "\n") {
		w.line("%s %s", stepName, expr.GroovyString(c.tr.Interpolate(script, true)))
		return
	}
	var body string
	if prefix != "" || strings.Contains(script, "<<") {
		// Shebangs must start the script and heredoc terminators must not be
		// indented, so keep the script exactly as written.
		body = prefix + script + "\n"
	} else {
		inner := w.pad() + indentUnit
		var b strings.Builder
		b.WriteByte('\n')
		for _, l := range strings.Split(script, "\n") {
			if strings.TrimSpace(l) != "" {
				b.WriteString(inner + l)
			}
			b.WriteByte('\n')
		}
		b.WriteString(w.pad())
		body = b.String()
	}
	w.line("%s %s", stepName, expr.TripleQuoted(c.tr.Interpolate(body, true)))
}

func (c *converter) with(s workflow.Step, key string) (string, bool) {
	v, ok := s.With.Get(key)
	if !ok {
		return "", false
	}
	return expr.GroovyString(c.tr.Interpolate(v, false)), true
}

// artifactPatterns converts upload-artifact paths into the directory to run
// stash/archiveArtifacts in and a comma-separated Ant include pattern.
//
// GitHub stores files relative to the least common ancestor of all the
// paths, so uploading `dist/` and downloading into `got/` yields
// `got/<file>`, not `got/dist/<file>`. Running stash inside that ancestor
// reproduces the layout. A path without a wildcard or trailing slash is
// treated as a file when its last segment has an extension, and as a
// directory otherwise.
func artifactPatterns(paths string) (root, includes string) {
	type entry struct {
		segs []string // full path segments
		base int      // number of leading literal directory segments
		dir  bool     // whole path names a directory
	}
	var entries []entry
	for _, p := range strings.Split(paths, "\n") {
		p = strings.TrimSpace(p)
		if p == "" || strings.HasPrefix(p, "!") {
			continue // exclusions are reported by the caller
		}
		p = strings.TrimPrefix(p, "./")
		dir := strings.HasSuffix(p, "/")
		segs := strings.Split(strings.Trim(p, "/"), "/")
		base := len(segs)
		for i, sg := range segs {
			if strings.ContainsAny(sg, "*?[{") {
				base = i
				break
			}
		}
		if base == len(segs) && !dir {
			if strings.Contains(segs[len(segs)-1], ".") {
				base-- // a file: its parent is the root
			} else {
				dir = true
			}
		}
		entries = append(entries, entry{segs, base, dir})
	}
	if len(entries) == 0 {
		return "", ""
	}
	common := entries[0].segs[:entries[0].base]
	for _, e := range entries[1:] {
		n := 0
		for n < len(common) && n < e.base && common[n] == e.segs[n] {
			n++
		}
		common = common[:n]
	}
	var out []string
	for _, e := range entries {
		rel := strings.Join(e.segs[len(common):], "/")
		switch {
		case e.dir && rel == "":
			rel = "**"
		case e.dir:
			rel += "/**"
		}
		out = append(out, rel)
	}
	return strings.Join(common, "/"), strings.Join(out, ",")
}

func (c *converter) uses(w *writer, j *workflow.Job, s workflow.Step) {
	action, _, _ := strings.Cut(s.Uses, "@")
	switch {
	case strings.EqualFold(action, "actions/checkout"):
		if repo, ok := s.With.Get("repository"); ok {
			c.warn("job %q: checkout of another repository (%s) needs a git step with credentials", j.ID, repo)
			w.todo("check out %s", repo)
		}
		w.line("checkout scm")

	case strings.EqualFold(action, "actions/upload-artifact"):
		name, ok := c.with(s, "name")
		if !ok {
			name = "'artifact'"
		}
		pathRaw, _ := s.With.Get("path")
		if strings.Contains(pathRaw, "!") {
			c.warn("job %q: upload-artifact exclusion patterns (!) were dropped; add 'excludes:' to stash/archiveArtifacts", j.ID)
		}
		root, includes := artifactPatterns(pathRaw)
		patterns := expr.GroovyString(c.tr.Interpolate(includes, false))
		allowEmpty := "true"
		if v, _ := s.With.Get("if-no-files-found"); v == "error" {
			allowEmpty = "false"
		}
		if root != "" {
			w.open("dir(%s)", expr.GroovyString(c.tr.Interpolate(root, false)))
		}
		w.line("stash name: %s, includes: %s, allowEmpty: %s", name, patterns, allowEmpty)
		w.line("archiveArtifacts artifacts: %s, allowEmptyArchive: %s", patterns, allowEmpty)
		if root != "" {
			w.close()
		}

	case strings.EqualFold(action, "actions/download-artifact"):
		name, ok := c.with(s, "name")
		if !ok {
			c.warn("job %q: download-artifact without a name downloads everything; unstash each artifact explicitly", j.ID)
			w.todo("unstash every artifact uploaded earlier")
			w.line("echo 'TODO(jenkinsfy): unstash artifacts'")
			return
		}
		if path, ok := c.with(s, "path"); ok {
			w.open("dir(%s)", path)
			w.line("unstash %s", name)
			w.close()
			return
		}
		w.line("unstash %s", name)

	case strings.HasPrefix(strings.ToLower(action), "actions/setup-"):
		tool := strings.TrimPrefix(strings.ToLower(action), "actions/setup-")
		c.warn("job %q: %s: install %s on the agent, use the 'tools' directive or a docker agent", j.ID, s.Uses, tool)
		w.todo("%s%s: provide %s via 'tools {}' or a docker agent", s.Uses, describeWith(s.With), tool)
		w.line("echo %s", expr.QuoteString("TODO(jenkinsfy): set up "+tool))

	case strings.EqualFold(action, "actions/cache"):
		c.warn("job %q: actions/cache has no direct equivalent; consider the Job Cacher plugin", j.ID)
		w.todo("%s%s has no direct equivalent", s.Uses, describeWith(s.With))
		w.line("echo 'TODO(jenkinsfy): cache'")

	case strings.HasPrefix(s.Uses, "docker://"):
		image := strings.TrimPrefix(s.Uses, "docker://")
		args, _ := s.With.Get("args")
		w.open("script")
		w.open("docker.image(%s).inside", expr.QuoteString(image))
		if args != "" {
			w.line("sh %s", expr.GroovyString(c.tr.Interpolate(args, true)))
		} else {
			c.warn("job %q: %s runs the image entrypoint; add the command explicitly", j.ID, s.Uses)
			w.todo("run the entrypoint of %s", image)
			w.line("echo 'TODO(jenkinsfy): run image entrypoint'")
		}
		w.close()
		w.close()

	default:
		c.warn("job %q: action %s has no Jenkins equivalent", j.ID, s.Uses)
		w.todo("replace action %s%s", s.Uses, describeWith(s.With))
		w.line("echo %s", expr.QuoteString("TODO(jenkinsfy): "+s.Uses))
	}
}

func describeWith(with workflow.OrderedMap) string {
	if len(with) == 0 {
		return ""
	}
	parts := make([]string, len(with))
	for i, kv := range with {
		parts[i] = kv.Key + ": " + strings.ReplaceAll(kv.Value, "\n", " ")
	}
	return " (" + strings.Join(parts, ", ") + ")"
}
